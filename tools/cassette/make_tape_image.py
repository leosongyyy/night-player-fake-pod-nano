#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Convert the local cassette artwork into LVGL 9 const image descriptors.

The project follows the same offline-generation policy as ``tools/font``:
generated C files are committed to the repository and are **not** produced at
build time.  Two variants are supported:

* RGB565 (default): 320x320, 2 bytes/pixel -> 204800 B (200 KiB).
* I2 / 2-bit indexed (``--lq``): optional debug variant, ~25 KiB.

Both descriptors live in Flash (const arrays, XIP) and therefore never consume
PSRAM or the internal DMA pool.

Usage::

    python3 tools/cassette/make_tape_image.py
    python3 tools/cassette/make_tape_image.py --lq

Requires Pillow (``pip3 install pillow``).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover - dependency error path
    print("ERROR: Pillow is required (pip3 install pillow)", file=sys.stderr)
    raise SystemExit(2)


DEFAULT_SRC = Path(
    "/Volumes/mac_mini/龙虾/NightPlayer-S31-二次开发指引/assets/cassette/tape-original.png"
)
DEFAULT_OUT_DIR = Path(__file__).resolve().parents[2] / "main" / "core" / "image"

SIZE = 320
BYTES_PER_LINE = 24
LQ_COLORS = 4


def _c_array(name: str, data: bytes, comment: str) -> str:
    """Render a byte buffer as a compact C initializer."""
    lines = ["/* %s */" % comment,
             "LV_ATTRIBUTE_MEM_ALIGN const uint8_t %s[] = {" % name]
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset:offset + BYTES_PER_LINE]
        lines.append("    " + " ".join("0x%02x," % b for b in chunk))
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def _header(out_dir: Path) -> None:
    """Write (or refresh) the shared public header."""
    guard = "CASSETTE_TAPE_H"
    text = f"""#ifndef {guard}
#define {guard}

#include "lvgl.h"

#ifdef __cplusplus
extern "C" {{
#endif

/*
 * Generated by tools/cassette/make_tape_image.py -- DO NOT EDIT BY HAND.
 * 320x320 const images in Flash (XIP); neither variant uses PSRAM.
 */
extern const lv_image_dsc_t cas_tape_320;      /* RGB565, 200 KiB */
extern const lv_image_dsc_t cas_tape_320_lq;   /* 2-bit indexed, ~25 KiB */

#if defined(CONFIG_CASSETTE_TAPE_LQ) && CONFIG_CASSETTE_TAPE_LQ
#define CAS_TAPE_IMG  (&cas_tape_320_lq)
#else
#define CAS_TAPE_IMG  (&cas_tape_320)
#endif

#ifdef __cplusplus
}}
#endif

#endif /* {guard} */
"""
    (out_dir / "cassette_tape.h").write_text(text, encoding="utf-8")
    print("[ok] header: %s" % (out_dir / "cassette_tape.h"))


def _prologue() -> str:
    """LVGL header block, identical to core/image/default_cover.c."""
    return """#ifdef __has_include
    #if __has_include("lvgl.h")
        #ifndef LV_LVGL_H_INCLUDE_SIMPLE
            #define LV_LVGL_H_INCLUDE_SIMPLE
        #endif
    #endif
#endif

#if defined(LV_LVGL_H_INCLUDE_SIMPLE)
    #include "lvgl.h"
#else
    #include "lvgl/lvgl.h"
#endif

#include "core/image/cassette_tape.h"

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

"""


def _descriptor(symbol: str, map_name: str, cf: str, stride: int,
                data_size: int) -> str:
    return f"""/* LVGL 9 image descriptor: cf uses LV_COLOR_FORMAT_*, not the v8 enums. */
const lv_image_dsc_t {symbol} = {{
    .header.magic = LV_IMAGE_HEADER_MAGIC,
    .header.cf = {cf},
    .header.flags = 0,
    .header.w = {SIZE},
    .header.h = {SIZE},
    .header.stride = {stride},
    .data_size = {data_size},
    .data = {map_name},
}};
"""


def build_rgb565(src: Path, out_dir: Path) -> int:
    """Generate the full-colour RGB565 descriptor; return payload byte count."""
    image = Image.open(src).convert("RGB")
    if image.size != (2048, 2048):
        print("[warn] unexpected source size %s, resizing anyway" % (image.size,))
    image = image.resize((SIZE, SIZE), Image.Resampling.LANCZOS)

    pixels = image.tobytes()
    out = bytearray(SIZE * SIZE * 2)
    dst = 0
    for i in range(0, len(pixels), 3):
        r, g, b = pixels[i], pixels[i + 1], pixels[i + 2]
        rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        out[dst] = rgb565 & 0xFF          # little endian (ESP32 / LVGL fast path)
        out[dst + 1] = rgb565 >> 8
        dst += 2

    body = _prologue()
    body += _c_array(
        "cas_tape_320_map",
        bytes(out),
        "%dx%d RGB565 (little endian) = %d bytes" % (SIZE, SIZE, len(out)),
    )
    body += _descriptor("cas_tape_320", "cas_tape_320_map",
                        "LV_COLOR_FORMAT_RGB565", SIZE * 2, len(out))
    path = out_dir / "cassette_tape.c"
    path.write_text(body, encoding="utf-8")
    print("[ok] %s: %d bytes (%.1f KiB), w=%d h=%d stride=%d"
          % (path, len(out), len(out) / 1024.0, SIZE, SIZE, SIZE * 2))
    return len(out)


def build_lq(src: Path, out_dir: Path) -> int:
    """Generate the optional 2-bit indexed descriptor; return total byte count."""
    image = Image.open(src).convert("RGB").resize(
        (SIZE, SIZE), Image.Resampling.LANCZOS
    )
    quant = image.quantize(colors=LQ_COLORS, method=Image.Quantize.MEDIANCUT)

    palette = quant.getpalette() or [0, 0, 0] * LQ_COLORS
    raw = bytearray()
    for idx in range(LQ_COLORS):
        r, g, b = palette[idx * 3:idx * 3 + 3]
        raw.extend((r, g, b, 0xFF))  # lv_color32_t palette entry

    # P-mode tobytes() yields one palette index per pixel (no Pillow 14
    # deprecation warning, unlike getdata()).
    indices = quant.tobytes()
    stride = (SIZE * 2 + 7) // 8
    for y in range(SIZE):
        packed = bytearray(stride)
        for x in range(SIZE):
            value = indices[y * SIZE + x] & 0x03
            shift = 6 - 2 * (x % 4)  # LVGL I2 packs the leftmost pixel in bits 7:6
            packed[x // 4] |= value << shift
        raw.extend(packed)

    body = _prologue()
    body += _c_array(
        "cas_tape_320_lq_map",
        bytes(raw),
        "%dx%d I2 (4-colour palette + packed indices) = %d bytes"
        % (SIZE, SIZE, len(raw)),
    )
    body += _descriptor("cas_tape_320_lq", "cas_tape_320_lq_map",
                        "LV_COLOR_FORMAT_I2", stride, len(raw))
    path = out_dir / "cassette_tape_lq.c"
    path.write_text(body, encoding="utf-8")
    print("[ok] %s: %d bytes (%.1f KiB), w=%d h=%d stride=%d"
          % (path, len(raw), len(raw) / 1024.0, SIZE, SIZE, stride))
    return len(raw)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, default=DEFAULT_SRC,
                        help="source PNG (default: %(default)s)")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR,
                        help="output directory (default: %(default)s)")
    parser.add_argument("--lq", action="store_true",
                        help="also generate the 2-bit indexed variant")
    args = parser.parse_args()

    if not args.src.is_file():
        print("ERROR: source image not found: %s" % args.src, file=sys.stderr)
        return 2
    args.out_dir.mkdir(parents=True, exist_ok=True)

    _header(args.out_dir)
    rgb565_size = build_rgb565(args.src, args.out_dir)
    lq_size = build_lq(args.src, args.out_dir) if args.lq else 0

    expected = SIZE * SIZE * 2
    print("--- size check ---")
    print("  RGB565 payload : %d B (expected %d B) -> %s"
          % (rgb565_size, expected,
             "PASS" if rgb565_size == expected else "FAIL"))
    if lq_size:
        print("  I2 payload     : %d B (expected %d B) -> %s"
              % (lq_size, 16 + SIZE * ((SIZE * 2 + 7) // 8),
                 "PASS" if lq_size == 16 + SIZE * ((SIZE * 2 + 7) // 8)
                 else "FAIL"))
    return 0 if rgb565_size == expected else 1


if __name__ == "__main__":
    raise SystemExit(main())
