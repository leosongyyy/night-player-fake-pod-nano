#!/usr/bin/env bash
# ============================================================================
# Bake the retro Chinese + true-monospace + symbol subsets for the cassette UI.
#
# All font sources are freely redistributable and live in assets/fonts/ with
# their license texts.  The script stays non-blocking: if a TTF or
# lv_font_conv is missing it prints SKIP and exits 0, leaving the project on
# CONFIG_CASSETTE_FONT_FALLBACK (UI_SYSTEM_FONT + Montserrat).
#
#   CN   : ZCOOL QingKe HuangYou (站酷庆科黄油体)   - Chinese body
#   MONO : JetBrains Mono Regular                  - true monospace digits
#   SYM  : DejaVu Sans                             - 7 UI glyphs missing from
#                                                   ZCOOL (·■▲►◄⚙❚)
# Override with ZCOOL_TTF=... / MONO_TTF=... / SYM_TTF=... / LV_FONT_CONV=... .
#
# Fallback chain: cas_font_mono -> cas_font_cn -> cas_font_sym.
#
# Generated outputs (registered automatically by main/CMakeLists.txt):
#   main/core/fonts/cassette_font_cn_baked.c
#   main/core/fonts/cassette_font_mono_baked.c
#   main/core/fonts/cassette_font_sym_baked.c
#   main/core/fonts/cassette_font_baked.h
# ============================================================================
set -u

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
OUT_DIR="${REPO_ROOT}/main/core/fonts"
GLYPHS="${SCRIPT_DIR}/glyphs_cn.txt"
MONO_GLYPHS="${SCRIPT_DIR}/glyphs_mono.txt"
SYM_GLYPHS="${SCRIPT_DIR}/glyphs_sym.txt"
ZCOOL_TTF="${ZCOOL_TTF:-${REPO_ROOT}/assets/fonts/ZCOOLQingKeHuangYou-Regular.ttf}"
MONO_TTF="${MONO_TTF:-${REPO_ROOT}/assets/fonts/JetBrainsMono-Regular.ttf}"
SYM_TTF="${SYM_TTF:-${REPO_ROOT}/assets/fonts/DejaVuSans.ttf}"
LV_FONT_CONV="${LV_FONT_CONV:-lv_font_conv}"
FALLBACK_HINT="Using CONFIG_CASSETTE_FONT_FALLBACK instead (UI_SYSTEM_FONT / &lv_font_montserrat_24)."

echo "[cassette-font] repo: ${REPO_ROOT}"

if [ ! -f "${GLYPHS}" ] || [ ! -f "${SYM_GLYPHS}" ]; then
    echo "[cassette-font] SKIP: glyph list missing (${GLYPHS} / ${SYM_GLYPHS})"
    echo "[cassette-font] ${FALLBACK_HINT}"
    exit 0
fi

if [ ! -f "${ZCOOL_TTF}" ] || [ ! -f "${SYM_TTF}" ]; then
    echo "[cassette-font] SKIP: font source not found (${ZCOOL_TTF} / ${SYM_TTF})"
    echo "[cassette-font] ${FALLBACK_HINT}"
    exit 0
fi

if ! command -v "${LV_FONT_CONV}" >/dev/null 2>&1; then
    echo "[cassette-font] SKIP: ${LV_FONT_CONV} not on PATH."
    echo "[cassette-font] Install with: npm i -g lv_font_conv  (v1.5.3 tested)"
    echo "[cassette-font] ${FALLBACK_HINT}"
    exit 0
fi

mkdir -p "${OUT_DIR}"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "${TMP_DIR}"' EXIT

license_header() {
    echo '/* Generated by tools/cassette/bake_font.sh -- DO NOT EDIT BY HAND. */'
    echo '/*'
    echo ' * Font subsets distributed with this firmware:'
    echo ' *   cas_font_cn   : ZCOOL QingKe HuangYou (站酷庆科黄油体) - SIL OFL 1.1'
    echo ' *   cas_font_mono : JetBrains Mono Regular - SIL OFL 1.1'
    echo ' *   cas_font_sym  : DejaVu Sans - Bitstream Vera / Arev (see LICENSE)'
    echo ' * License texts: assets/fonts/ZCOOLQingKeHuangYou-OFL.txt'
    echo ' *                assets/fonts/JetBrainsMono-OFL.txt'
    echo ' *                assets/fonts/DejaVuSans-LICENSE.txt'
    echo ' */'
}

# Each font occupies its own .c: lv_font_conv emits file-static glyph_bitmap,
# glyph_dsc, cmaps, ... so concatenating outputs would redefine every symbol.

# 1. Symbol subset first: ZCOOL lacks 7 UI glyphs (·■▲►◄⚙❚); the mono font
#    covers only ·■▲►◄, so the sym subset is mandatory, not cosmetic.
echo "[cassette-font] baking CAS_FONT_SYM (DejaVu Sans, 24px/bpp2, 7 glyphs) ..."
"${LV_FONT_CONV}" \
    --font "${SYM_TTF}" \
    --size 24 --bpp 2 \
    --format lvgl --lv-include lvgl.h \
    --symbols "$(tr -d '\n\r' < "${SYM_GLYPHS}")" \
    --lv-font-name cas_font_sym \
    -o "${TMP_DIR}/sym.c" || {
        echo "[cassette-font] SKIP: lv_font_conv failed for the symbol subset."
        echo "[cassette-font] ${FALLBACK_HINT}"
        exit 0
    }
{ license_header; cat "${TMP_DIR}/sym.c"; } > "${OUT_DIR}/cassette_font_sym_baked.c"

# 2. Chinese body: fall back to the symbol subset for its 7 missing glyphs.
echo "[cassette-font] baking CAS_FONT_CN (ZCOOL QingKe HuangYou, 24px/bpp2) ..."
"${LV_FONT_CONV}" \
    --font "${ZCOOL_TTF}" \
    --size 24 --bpp 2 \
    --format lvgl --lv-include lvgl.h \
    --symbols "$(tr -d '\n\r' < "${GLYPHS}")" \
    --lv-font-name cas_font_cn \
    --lv-fallback cas_font_sym \
    -o "${TMP_DIR}/cn.c" || {
        echo "[cassette-font] SKIP: lv_font_conv failed for the Chinese subset."
        echo "[cassette-font] ${FALLBACK_HINT}"
        exit 0
    }
{ license_header; cat "${TMP_DIR}/cn.c"; } > "${OUT_DIR}/cassette_font_cn_baked.c"

# 3. True monospace digits: fall back to the Chinese subset (which itself
#    falls back to sym), so mixed glyphs such as ⚙/❚ still render.
echo "[cassette-font] baking CAS_FONT_MONO (JetBrains Mono, 24px/bpp2) ..."
MONO_BAKED=0
if [ -f "${MONO_TTF}" ] && [ -f "${MONO_GLYPHS}" ]; then
    if "${LV_FONT_CONV}" \
        --font "${MONO_TTF}" \
        --size 24 --bpp 2 \
        --format lvgl --lv-include lvgl.h \
        --symbols "$(tr -d '\n\r' < "${MONO_GLYPHS}")" \
        --lv-font-name cas_font_mono \
        --lv-fallback cas_font_cn \
        -o "${TMP_DIR}/mono.c"; then
        { license_header; cat "${TMP_DIR}/mono.c"; } \
            > "${OUT_DIR}/cassette_font_mono_baked.c"
        MONO_BAKED=1
    else
        echo "[cassette-font] WARN: mono subset failed, reusing Montserrat 24."
    fi
else
    echo "[cassette-font] WARN: mono source missing, reusing Montserrat 24."
fi
if [ "${MONO_BAKED}" -eq 0 ]; then
    rm -f "${OUT_DIR}/cassette_font_mono_baked.c"
fi

cat > "${OUT_DIR}/cassette_font_baked.h" <<'EOF'
#ifndef CASSETTE_FONT_BAKED_H
#define CASSETTE_FONT_BAKED_H
#include "lvgl.h"
#ifdef __cplusplus
extern "C" {
#endif
extern const lv_font_t cas_font_sym;   /* DejaVu Sans: ·■▲►◄⚙❚ */
extern const lv_font_t cas_font_cn;    /* fallback -> cas_font_sym */
EOF
if [ "${MONO_BAKED}" -eq 1 ]; then
    echo '#define CASSETTE_FONT_BAKED_HAS_MONO 1' >> "${OUT_DIR}/cassette_font_baked.h"
    echo 'extern const lv_font_t cas_font_mono;' >> "${OUT_DIR}/cassette_font_baked.h"
fi
cat >> "${OUT_DIR}/cassette_font_baked.h" <<'EOF'
#ifdef __cplusplus
}
#endif
#endif /* CASSETTE_FONT_BAKED_H */
EOF

echo "[cassette-font] OK: wrote cassette_font_{sym,cn,mono}_baked.c + cassette_font_baked.h"
echo "[cassette-font] Next: build with CONFIG_CASSETTE_FONT_FALLBACK=n."
exit 0
