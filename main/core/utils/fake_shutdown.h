#ifndef FAKE_SHUTDOWN_H
#define FAKE_SHUTDOWN_H

/* ------------------------------------------------------------------ */
/* 关机模块（当前为 S31 占位实现）                                       */
/*                                                                     */
/* S3 旧板：没有独立 PMIC，固件用"伪关机"近似关机——关外设后进入           */
/*   deepsleep，按 B 键（GPIO0/RTC）唤醒重启；A 键长按则由电源侧 3 秒     */
/*   关机芯片硬件断电。                                                  */
/*                                                                     */
/* S31 新板（FakePodNano Pro V1）：关机/开机由 **AXP2101** 电源管理芯片   */
/*   控制（上方电源键接 AXP2101，不再有独立主控 GPIO），deep sleep 唤醒  */
/*   源也不同。2026-11 平台迁移阶段 AXP2101 尚未适配，因此本模块只保留   */
/*   API 占位：两个入口都只打印日志并返回，不做任何硬件动作。            */
/*                                                                     */
/* ⚠ 当前固件的睡眠定时器到点改为"停播 + 息屏"（见 core/utils/sleep_timer.c），*/
/*   不再调用本模块；低电自动关机、电源键长按关机也已移除。AXP2101 适配时 */
/*   在本文件实现真正的关机（读 PMU 按键事件 / 配置关机寄存器）即可。     */
/* ------------------------------------------------------------------ */

/* 普通关机（预留：睡眠定时器/自动关机策略调用）。
   当前占位实现：只打印日志，立即返回。 */
void fake_shutdown_enter(void);

/* "等待电源键断电"关机（预留：AXP2101 电源键长按流程调用）。
   当前占位实现：只打印日志，立即返回。 */
void fake_shutdown_wait_power_off(void);

#endif /* FAKE_SHUTDOWN_H */
