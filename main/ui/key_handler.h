/**
 * @file key_handler.h
 * @brief 应用层按键分发（亮屏/息屏两套按键映射）
 *
 * 亮屏状态：
 *   - A 键（GPIO48，上键）短按：音量 +
 *   - B 键（GPIO0，下键）短按：音量 -
 *   - A 键长按：伪关机（等待断电，屏幕定格提示，配合 3 秒关机芯片）
 *     阈值：亮屏 KEY_A_LONG_PRESS_ON_MS（1200ms）
 *   - B 键长按：音量一次性 -10 档（B 键可安全长按；音量 0~30 档）
 *   - 双键同时按下：息屏
 * 息屏状态（黑屏播放，按键盲操作）：
 *   - A 键短按：播放 / 暂停
 *   - B 键短按：下一曲
 *   - B 键长按：上一曲（B 键可安全长按）
 *   - A 键长按：先亮屏再伪关机（点亮屏幕显示保存/关机提示，计划第 6 点）
 *     阈值：息屏 KEY_A_LONG_PRESS_OFF_MS（900ms，比亮屏更短，见宏注释）
 *   - 双键同时按下：亮屏
 *
 * 所有按键事件都会记录为一次"用户活动"（刷新自动息屏计时，
 * 见 core/utils/power_service）。
 *
 * 唤醒防循环：deepsleep 唤醒 = 芯片重启，若唤醒时按键仍被按住，开机后
 * 去抖仍会报告事件 → 立即再次休眠；故开机 1.2 秒内忽略按键事件。
 */

/* ------------------------------------------------------------------ */
/* A 键（电源键/上键）长按阈值（ms）                                    */
/*                                                                     */
/* 约束（改任何一项前必读）：                                           */
/*   阈值 + 亮屏耗时（AMOLED SLEEP OUT 重初始化 + 全屏重刷，实测数百 ms） */
/*   + 保存耗时（NVS 写 + 停解码/DAC/触摸/SD，实测数百 ms）              */
/*   必须明显小于 3000ms —— 那是电源侧关机芯片的硬断电时刻，凑太紧就会  */
/*   出现"屏幕提示一闪而过、配置还没落盘就断电"。                        */
/* ------------------------------------------------------------------ */

/* 亮屏态阈值：1200ms。
   历次实测：曾用 2000ms，用户按满 3s 断电时提示只显示一秒甚至一闪而过
   （伪关机流程本身还要耗时），降到 1200ms 后提示窗口约 1.8s，容易看清。 */
#define KEY_A_LONG_PRESS_ON_MS      1200

/* 息屏态阈值：900ms。
   比亮屏更短，原因是息屏长按要**先点亮屏幕**（AMOLED SLEEP OUT 重初始化
   + 全屏重刷）再走伪关机保存流程，亮屏那数百 ms 必须从 3 秒窗口里省回来，
   否则极罕见情况下会出现"来不及保存就断电"（用户 2026-11 实测反馈）。
   代价：息屏下按住 900~1200ms 的按压会走关机而不再是"播放/暂停"，
   若误触偏多，往上微调到 1000ms 左右即可。 */
#define KEY_A_LONG_PRESS_OFF_MS      900

/* B 键（下键）长按阈值：固定 600ms，在 core/hardware/button_service.c 里
   （亮屏=音量-10 / 息屏=上一曲，缩短阈值提升响应；B 键可安全长按）。 */

/**
 * @brief 初始化按键分发：注册 button_service 按键事件回调
 *
 * 需在 button_service_init() 之后调用（内部调用 button_service_register_cb）。
 */
void key_handler_init(void);

